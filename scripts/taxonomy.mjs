function byName(name) {
  const n = String(name || '');
  for (const [re, value] of RULES) {
    if (re.test(n)) return value;
  }
  return null;
}

export function classify(product) {
  const guess = byName(product.name);
  if (guess) return guess;

  const mapped = SUB_MAP[product.subcategory];
  if (mapped) return mapped;

  if (product.parent === 'Одежда и текстиль') return ['Одежда и текстиль', 'Женская одежда'];
  if (product.parent === 'Обувь и уход') return ['Обувь', 'Тапочки'];
  if (product.parent === 'Посуда') return ['Посуда', 'Разное'];
  if (product.parent === 'Канцелярские товары') return ['Канцелярия', 'Разное'];
  if (product.parent === 'Продукты и напитки') return ['Продукты', 'Продукты'];
  if (product.parent === 'Аксессуары') return ['Аксессуары', 'Разное'];

  return ['Ассортимент', 'Разное'];
}
